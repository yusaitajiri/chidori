//! Writes the kamon tokens (`brand/tokens.json`, from the kit) as Rust constants with Chidori's
//! accent, and gives the Windows exe its icon.

use std::fmt::Write;
use std::path::Path;

const APP: &str = "chidori";

fn main() {
    let src = Path::new("brand/tokens.json");
    println!("cargo:rerun-if-changed={}", src.display());
    let json: serde_json::Value = serde_json::from_str(&std::fs::read_to_string(src).unwrap()).unwrap();

    let app_color = json["apps"]["list"].as_array().unwrap().iter().find(|a| a["id"] == APP).unwrap()["color"]
        .as_str()
        .unwrap()
        .to_owned();

    let colors = json["color"]["tokens"].as_array().unwrap();
    let lookup = |name: &str, theme: &str| -> String {
        let mut name = name.to_owned();
        // accent* points at the app's color family.
        if let Some(rest) = name.strip_prefix("accent") {
            name = format!("{app_color}{rest}");
        } else if name == "on-accent" {
            name = format!("on-{app_color}");
        }
        loop {
            let t = colors.iter().find(|t| t["name"] == name.as_str()).unwrap();
            let v = t["value"][theme].as_str().unwrap();
            match v.strip_prefix('{').and_then(|v| v.strip_suffix('}')) {
                Some(r) => name = r.to_owned(),
                None => return v.to_owned(),
            }
        }
    };

    let mut out = String::from("// Generated by build.rs from tokens.json. Don't edit.\n\n");
    out.push_str("#[derive(Debug, Clone, Copy)]\npub struct Palette {\n");
    for t in colors {
        writeln!(out, "    pub {}: Color,", ident(t["name"].as_str().unwrap())).unwrap();
    }
    out.push_str("}\n\n");
    for theme in ["light", "dark"] {
        writeln!(out, "pub const {}: Palette = Palette {{", theme.to_uppercase()).unwrap();
        for t in colors {
            let name = t["name"].as_str().unwrap();
            let hex = lookup(name, theme);
            let [r, g, b] = [1, 3, 5].map(|i| u8::from_str_radix(&hex[i..i + 2], 16).unwrap() as f32 / 255.0);
            writeln!(out, "    {}: Color {{ r: {r:?}, g: {g:?}, b: {b:?}, a: 1.0 }},", ident(name)).unwrap();
        }
        out.push_str("};\n\n");
    }

    for group in ["spacing", "radius"] {
        for t in json[group]["tokens"].as_array().unwrap() {
            let px = t["value"].as_str().unwrap().trim_end_matches("px");
            writeln!(out, "pub const {}: f32 = {px}.0;", ident(t["name"].as_str().unwrap()).to_uppercase()).unwrap();
        }
    }

    out.push_str("\n#[derive(Debug, Clone, Copy)]\npub struct TypeStyle {\n    pub size: f32,\n    pub line_height: f32,\n    pub medium: bool,\n    pub mono: bool,\n}\n\n");
    for g in json["type"]["groups"].as_array().unwrap() {
        for s in g["styles"].as_array().unwrap() {
            let name = s["name"].as_str().unwrap();
            let size = s["fontSize"].as_str().unwrap().trim_end_matches("px");
            let lh = s["lineHeight"].as_str().unwrap().trim_end_matches("px");
            let medium = s["fontWeight"].as_u64().unwrap() >= 500;
            writeln!(
                out,
                "pub const {}: TypeStyle = TypeStyle {{ size: {size}.0, line_height: {lh}.0, medium: {medium}, mono: {} }};",
                ident(name).to_uppercase(),
                name == "mono"
            )
            .unwrap();
        }
    }

    let dest = Path::new(&std::env::var("OUT_DIR").unwrap()).join("tokens.rs");
    std::fs::write(dest, out).unwrap();

    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows") {
        println!("cargo:rerun-if-changed=icons/icon.ico");
        let mut res = winresource::WindowsResource::new();
        res.set_icon("icons/icon.ico");
        res.compile().expect("compiling the Windows resources");
    }
}

fn ident(name: &str) -> String {
    name.replace('-', "_")
}
